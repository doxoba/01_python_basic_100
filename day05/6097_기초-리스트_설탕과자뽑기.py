#       ------
#       부모님과 함께 놀러간 영일이는
#       설탕과자(설탕을 녹여 물고기 등의 모양을 만든 것) 뽑기를 보게 되었다.
#       길이가 다른 몇 개의 막대를 바둑판과 같은 격자판에 놓는데,
#       막대에 있는 설탕과자 이름 아래에 있는 번호를 뽑으면 설탕과자를 가져가는 게임이었다.
#       (잉어, 붕어, 용 등 여러 가지가 적혀있다.)
#       격자판의 세로(h), 가로(w), 막대의 개수(n), 각 막대의 길이(l),
#       막대를 놓는 방향(d:가로는 0, 세로는 1)과
#       막대를 놓는 막대의 가장 왼쪽 또는 위쪽의 위치(x, y)가 주어질 때,
#       격자판을 채운 막대의 모양을 출력하는 프로그램을 만들어보자.
#       [입력]
#       첫 줄에 격자판의 세로(h), 가로(w) 가 공백을 두고 입력되고,
#       두 번째 줄에 놓을 수 있는 막대의 개수(n)
#       세 번째 줄부터 각 막대의 길이(l), 방향(d), 좌표(x, y)가 입력된다.
#       1 <= w, h <= 100
#       1 <= n <= 10
#       d = 0 or 1
#       1 <= x <= 100-h
#       1 <= y <= 100-w
#       [출력]
#       모든 막대를 놓은 격자판의 상태를 출력한다.
#       막대에 의해 가려진 경우 1, 아닌 경우 0으로 출력한다.
#       단, 각 숫자는 공백으로 구분하여 출력한다.
# ---------------------------------------------------------
# (여기에 내 풀이)
# 1. 격자판 세로 h, 가로 w 입력받기
h, w = input().split()
h = int(h)
w = int(w)

# 2. h x w 크기의 격자판을 0으로 채우기
# 좌표가 1번부터 시작하므로 인덱스를 맞추기 위해 (h + 1) x (w + 1) 크기로 생성
board = []
for i in range(h + 1):
    board.append([])
    for j in range(w + 1):
        board[i].append(0)

# 3. 막대의 개수 n 입력받기
n = int(input())

# 4. n개의 막대 정보를 하나씩 처리하기
for _ in range(n):
    l, d, x, y = input().split()
    l = int(l)  # 막대 길이
    d = int(d)  # 방향 (0: 가로, 1: 세로)
    x = int(x)  # 시작 행 (세로 위치)
    y = int(y)  # 시작 열 (가로 위치)
    
    # 막대 길이(l)만큼 칸을 채우기
    for k in range(l):
        if d == 0:
            # 가로 방향: 행(x)은 그대로 두고 열(y)만 1씩 오른쪽으로 이동
            board[x][y + k] = 1
        else:
            # 세로 방향: 열(y)은 그대로 두고 행(x)만 1씩 아래쪽으로 이동
            board[x + k][y] = 1

# 5. 완성된 격자판을 1행부터 h행까지, 1열부터 w열까지 줄바꿈하며 출력
for i in range(1, h + 1):
    for j in range(1, w + 1):
        print(board[i][j], end=' ')
    print()


