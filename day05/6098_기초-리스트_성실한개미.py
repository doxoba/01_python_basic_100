#       ------
#       영일이는 생명과학에 관심이 생겨 왕개미를 연구하고 있었다.
#       왕개미를 유심히 살펴보던 중 특별히 성실해 보이는 개미가 있었는데,
#       그 개미는 개미굴에서 나와 먹이까지 가장 빠른 길로 이동하는 것이었다.
#       개미는 오른쪽으로 움직이다가 벽을 만나면 아래쪽으로 움직여 가장 빠른 길로 움직였다.
#       (오른쪽에 길이 나타나면 다시 오른쪽으로 움직인다.)
#       이에 호기심이 생긴 영일이는 그 개미를 미로 상자에 넣고 살펴보기 시작하였다.
#       미로 상자에 넣은 개미는 먹이를 찾았거나, 더 이상 움직일 수 없을 때까지
#       오른쪽 또는 아래쪽으로만 움직였다.
#       미로 상자의 구조가 0(갈 수 있는 곳), 1(벽 또는 장애물)로 주어지고,
#       먹이가 2로 주어질 때, 성실한 개미의 이동 경로를 예상해보자.
#       단, 맨 아래의 가장 오른쪽에 도착한 경우, 더 이상 움직일 수 없는 경우, 먹이를 찾은 경우에는
#       더이상 이동하지 않고 그 곳에 머무른다고 가정한다.
#       미로 상자의 테두리는 모두 벽으로 되어 있으며,
#       개미집은 반드시 (2, 2)에 존재하기 때문에 개미는 (2, 2)에서 출발한다.
#       [입력]
#       10*10 크기의 미로 상자의 구조와 먹이의 위치가 입력된다.
#       [출력]
#       성실한 개미가 이동한 경로를 9로 표시해 출력한다.
# ---------------------------------------------------------
# 1. 10x10 크기의 미로 상자 입력받기
board = []
for _ in range(10):
    row_words = input().split()
    row = []
    for num_str in row_words:
        row.append(int(num_str))
    board.append(row)

# 2. 개미의 출발 위치 설정 (문제 조건: 2, 2 -> 0번 인덱스 기준으로는 1, 1)
x = 1
y = 1

# 3. 개미 이동 시뮬레이션 (while True)
while True:
    # 현재 위치가 먹이(2)라면 9로 찍고 즉시 탈출
    if board[x][y] == 2:
        board[x][y] = 9
        break
    
    # 먹이가 아니라면 현재 위치를 9로 표시
    board[x][y] = 9
    
    # 이동 우선순위 1: 오른쪽(y + 1)으로 갈 수 있는지 확인 (벽인 1이 아닐 때)
    if board[x][y + 1] != 1:
        y += 1
    # 이동 우선순위 2: 오른쪽이 막혔다면 아래쪽(x + 1) 확인
    elif board[x + 1][y] != 1:
        x += 1
    # 오른쪽도 아래쪽도 모두 막혔다면 이동 불가 -> 탈출
    else:
        break

# 4. 최종 미로 판 출력하기
for i in range(10):
    for j in range(10):
        print(board[i][j], end=' ')
    print()# (여기에 내 풀이)



